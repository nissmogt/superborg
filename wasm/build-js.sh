#!/bin/sh
# Build the engine as plain JavaScript (wasm2js), for pages whose security policy blocks
# WebAssembly compilation. About 3-5x slower than borg.wasm.
#
#   wasm/build-js.sh [out.js]      default: build/borg-asm.js
#
# Needs clang with the wasm32-wasi target and binaryen's wasm2js (BINARYEN_WASM2JS, or on PATH,
# or `npx -y binaryen@123.0.0`). The output defines borgAsmInstantiate(imports) for wasm/borg-runtime.js.
set -eu
cd "$(dirname "$0")/.."
OUT=${1:-build/borg-asm.js}
CC=${CC:-clang}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$(dirname "$OUT")"
$CC --target=wasm32-wasi -O3 -mcpu=mvp -mexec-model=reactor -std=c11 -fvisibility=hidden \
    -D_GNU_SOURCE -D_DEFAULT_SOURCE -DBORG_NO_THREADS -DBORG_NO_MMAP -D_WASI_EMULATED_MMAN -Iengine \
    engine/json.c engine/model.c engine/kernels.c engine/pool.c engine/tokenizer.c engine/forward.c \
    engine/sample.c engine/generate.c engine/json_mode.c \
    -o "$TMP/borg-mvp.wasm" -lm -lwasi-emulated-mman \
    -Wl,--export-dynamic -Wl,--export=malloc -Wl,--export=free -Wl,--max-memory=4294967296
if [ -n "${BINARYEN_WASM2JS:-}" ]; then W2J=$BINARYEN_WASM2JS
elif command -v wasm2js >/dev/null 2>&1; then W2J=wasm2js
else W2J="npx -y -p binaryen@123.0.0 wasm2js"; fi
$W2J "$TMP/borg-mvp.wasm" -O3 -o "$TMP/borg-esm.js"
# wasm2js writes an ES module that imports its WASI functions; turn it into a classic script
# (Web Workers started from blob: URLs cannot always load modules) exposing asmFunc.
python3 - "$TMP/borg-esm.js" "$OUT" <<'PY'
import re, sys
src = open(sys.argv[1]).read()
src = re.sub(r"^import \* as \w+ from '[^']+';\n", "", src, flags=re.M)
cut = src.index("var retasmFunc = asmFunc(")
body = src[:cut]
open(sys.argv[2], "w").write(
    "// Generated by wasm/build-js.sh (clang wasm32-wasi + binaryen wasm2js). Do not edit.\n"
    "(function (root) {\n" + body + "\nroot.borgAsmInstantiate = asmFunc;\n"
    "if (typeof module !== 'undefined' && module.exports) module.exports = { borgAsmInstantiate: asmFunc };\n"
    "})(typeof self !== 'undefined' ? self : globalThis);\n")
PY
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
